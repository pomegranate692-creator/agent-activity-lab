#!/usr/bin/env python3
"""Deterministic SIMULATED stress scenario (30 agents) in the same schema as scenario.json.
Use it with ?scenario=stress to see how a concept holds up when there are many agents."""
import json, os, random
HERE = os.path.dirname(os.path.abspath(__file__))
R = random.Random(11)
ev = []
def e(t, type_, **kw): ev.append({"t": int(t), "type": type_, **kw})
agents = []
def add(aid, name, label, role, parent, deps): agents.append(dict(id=aid, name=name, label=label, role=role, parentId=parent, dependsOn=deps))

TASK = {"id": "stress-1", "title": "Migrate 6 services to the new API", "goal": "Simulated stress run with many agents."}
e(0, "task_started", task=TASK)
add("orch", "Orchestrator", "ORCH", "Coordinates the migration", None, [])
svc = ["auth", "billing", "search", "inbox", "media", "reports"]
tools = ["read_file", "edit_file", "grep", "run_tests", "git_diff", "lint"]
t = 300
e(t, "agent_spawned", agentId="orch", name="Orchestrator", label="ORCH", role="Coordinates the migration", parentId=None, dependsOn=[])
e(t + 400, "tool_called", agentId="orch", tool="plan", input="6 services", durationMs=800)
prev_done = None
all_ids = ["orch"]
for i, s in enumerate(svc):
    lead = f"s{i}"
    deps = [] if i % 3 == 0 else [f"s{i - 1}"]
    add(lead, f"{s.title()} lead", s[:4].upper(), f"Migrates the {s} service", "orch", deps)
    t0 = 1500 + i * 900
    e(t0, "agent_spawned", agentId=lead, name=f"{s.title()} lead", label=s[:4].upper(), role=f"Migrates the {s} service", parentId="orch", dependsOn=deps)
    e(t0 + 50, "work_delegated", fromId="orch", toId=lead, workId="w-" + lead, description=f"Migrate {s}")
    all_ids.append(lead)
    subs = []
    for j in range(R.randint(3, 5)):
        sid = f"{lead}_{j}"; nm = ["Reader", "Editor", "Tester", "Linter", "Doc writer"][j % 5]
        add(sid, f"{s.title()} {nm.lower()}", f"{s[:2].upper()}{nm[0]}{j}", f"{nm} for {s}", lead, [])
        e(t0 + 300 + j * 120, "agent_spawned", agentId=sid, name=f"{s.title()} {nm.lower()}", label=f"{s[:2].upper()}{nm[0]}{j}", role=f"{nm} for {s}", parentId=lead, dependsOn=[])
        e(t0 + 330 + j * 120, "work_delegated", fromId=lead, toId=sid, workId="w-" + sid, description=f"{nm} the {s} service")
        subs.append(sid); all_ids.append(sid)
    # work
    cur = t0 + 900
    for sid in subs:
        for k in range(R.randint(1, 3)):
            e(cur, "tool_called", agentId=sid, tool=R.choice(tools), input=f"{s}/{R.randint(1, 40)}.ts", durationMs=900); cur += R.randint(500, 1400)
        if R.random() < 0.25 and sid.endswith("_2"):
            e(cur, "agent_failed", agentId=sid, error="type error in " + s); cur += 700
            e(cur, "agent_retry", agentId=sid, attempt=2); cur += 900
            e(cur, "tool_called", agentId=sid, tool="edit_file", input=f"{s}/fix.ts", durationMs=800); cur += 900
        if R.random() < 0.15:
            e(cur, "agent_blocked", agentId=sid, reason="Needs approval to modify prod config", needs="human approval"); cur += 2200
            e(cur, "agent_unblocked", agentId=sid, by="human approval"); cur += 300
        e(cur, "output_produced", agentId=sid, outputId="o-" + sid, name=f"{sid}.patch", kind="patch")
        e(cur + 100, "agent_completed", agentId=sid); cur += 250
        if R.random() < 0.6 and i > 0:
            e(cur, "message_sent", fromId=sid, toId=f"s{R.randint(0, i - 1)}", text="Shared helper changed")
    e(cur + 400, "output_produced", agentId=lead, outputId="o-" + lead, name=f"{s}-migration.md", kind="doc")
    e(cur + 500, "agent_completed", agentId=lead)
end = max(x["t"] for x in ev) + 800
e(end, "agent_completed", agentId="orch")
e(end + 200, "task_finished", status="succeeded", outputIds=[x["outputId"] for x in ev if x["type"] == "output_produced"], summary="All services migrated (simulated)")
ev.sort(key=lambda x: x["t"])
meta = {"title": TASK["title"], "source": "simulated", "sourceNote": "Scripted stress scenario (30 agents). No real agents are running.",
        "durationMs": ev[-1]["t"] + 1000, "agents": agents, "snapshotMs": int(ev[-1]["t"] * 0.5)}
doc = {"meta": meta, "events": ev}
json.dump(doc, open(os.path.join(HERE, "stress.json"), "w"))
open(os.path.join(HERE, "stress.js"), "w").write("// Generated by make_stress.py. SIMULATED.\nwindow.AGENT_SCENARIO_STRESS = " + json.dumps(doc) + ";\n")
print(len(agents), "agents,", len(ev), "events,", meta["durationMs"] // 1000, "s")
